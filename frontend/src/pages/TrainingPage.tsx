import { CheckCircle2, Database, Play, Save, XCircle } from 'lucide-react'
import { useState } from 'react'
import { CountBarChart, LikelihoodChart } from '../charts/Charts'
import { MatrixTable } from '../components/MatrixTable'
import { Button, Callout, Card, ErrorBox, Field, Loading, PageHeader, Stat, Tabs, inputCls } from '../components/ui'
import { useAppState } from '../hooks/useAppState'
import { useAction, useAsync } from '../hooks/useAsync'
import { BEHAVIOUR_SHORT, STATE_SHORT } from '../lib/constants'
import { fmt, pct } from '../lib/format'
import { api } from '../services/api'
import type { BaumWelchResponse, MLEResponse, ModelDict } from '../types'

type Method = 'mle' | 'baum-welch'
const f3 = (v: number | null) => (v === null ? 'n/a' : v.toFixed(3))

export function TrainingPage() {
  const { setModel } = useAppState()
  const summary = useAsync(() => api.datasetSummary(), [])
  const [method, setMethod] = useState<Method>('baum-welch')
  const [smoothing, setSmoothing] = useState(1)
  const [limit, setLimit] = useState<number | ''>('')
  const [maxIter, setMaxIter] = useState(200)
  const [tol, setTol] = useState(0.05)
  const [pseudo, setPseudo] = useState(0)
  const [init, setInit] = useState<'current' | 'random'>('current')
  const [seed, setSeed] = useState(7)
  const mle = useAction(api.trainMLE)
  const bw = useAction(api.trainBaumWelch)
  const save = useAction(api.saveParameters)
  const [saved, setSaved] = useState<string | null>(null)

  const result: MLEResponse | BaumWelchResponse | null = method === 'mle' ? mle.data : bw.data
  const running = mle.loading || bw.loading

  const run = () => {
    setSaved(null)
    const lim = limit === '' ? null : limit
    if (method === 'mle') mle.run({ smoothing, limit: lim })
    else bw.run({ max_iterations: maxIter, tolerance: tol, pseudocount: pseudo, init, seed, limit: lim })
  }

  const apply = async () => {
    if (!result) return
    const name = result.method === 'baum_welch' ? `Baum-Welch (${result.iterations} it.)` : `Supervised MLE (s=${result.smoothing})`
    const cfg = await save.run({ pi: result.after.pi, A: result.after.A, B: result.after.B, name })
    if (cfg) {
      setModel(cfg)
      setSaved(name)
    }
  }

  return (
    <div className="space-y-6">
      <PageHeader title="Model Training">
        Estimate λ = (A, B, π) from the synthetic dataset. <strong className="text-slate-200">Training</strong> changes the parameters using many sequences;{' '}
        <strong className="text-slate-200">inference</strong> (every other page) keeps them fixed and reasons about one customer.
      </PageHeader>

      <div className="grid grid-cols-1 gap-5 lg:grid-cols-[minmax(0,1fr)_minmax(0,1.3fr)]">
        <Card title="Training data" subtitle="600 simulated sequences generated by the backend (seed 42)" action={<Database className="size-4 text-slate-500" />}>
          {summary.loading ? (
            <Loading />
          ) : summary.data ? (
            <div className="space-y-4">
              <div className="grid grid-cols-3 gap-2">
                <Stat label="Sequences" value={summary.data.total} />
                <Stat label="Mean length" value={summary.data.mean_length.toFixed(1)} />
                <Stat label="Purchased" value={pct(summary.data.purchase_rate, 0)} />
              </div>
              <CountBarChart data={summary.data.behaviours.map((b) => ({ ...b, behaviour: BEHAVIOUR_SHORT[b.behaviour] ?? b.behaviour }))} xKey="behaviour" height={236} angled />
              <Callout kind="warn">The dataset is simulated. A model trained on it describes the simulator, not real customers.</Callout>
            </div>
          ) : (
            <ErrorBox error={summary.error} />
          )}
        </Card>

        <Card title="Training configuration">
          <div className="space-y-5">
            <Tabs
              tabs={[
                { id: 'baum-welch', label: 'Baum-Welch (unsupervised)' },
                { id: 'mle', label: 'Frequency MLE (supervised)' },
              ]}
              value={method}
              onChange={setMethod}
            />
            <p className="text-sm leading-relaxed text-slate-400">
              {method === 'mle'
                ? 'Uses the recorded hidden-state labels of each simulated sequence and counts transitions and emissions. Additive smoothing prevents zero probabilities for events not seen in the data.'
                : 'Ignores the hidden-state labels entirely. Starting from an initial λ, it alternates the E-step (Forward-Backward expected counts) and the M-step (re-estimation) until the log-likelihood stops improving by more than the tolerance.'}
            </p>
            <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
              <Field label="Sequences to use" hint="blank = all 600">
                <input className={inputCls} type="number" min={1} max={600} placeholder="all" value={limit} onChange={(e) => setLimit(e.target.value === '' ? '' : Math.max(1, Number(e.target.value)))} />
              </Field>
              {method === 'mle' ? (
                <Field label="Smoothing s" hint="pseudo-count added to every count">
                  <input className={inputCls} type="number" min={0} step={0.5} value={smoothing} onChange={(e) => setSmoothing(Math.max(0, Number(e.target.value)))} />
                </Field>
              ) : (
                <>
                  <Field label="Max iterations">
                    <input className={inputCls} type="number" min={1} max={500} value={maxIter} onChange={(e) => setMaxIter(Math.min(500, Math.max(1, Number(e.target.value))))} />
                  </Field>
                  <Field label="Convergence tolerance" hint="stop when Δ log L < tol">
                    <input className={inputCls} type="number" min={0.0000001} step="any" value={tol} onChange={(e) => setTol(Number(e.target.value))} />
                  </Field>
                  <Field label="Initial parameters">
                    <select className={inputCls.replace('num ', '')} value={init} onChange={(e) => setInit(e.target.value as 'current' | 'random')}>
                      <option value="current">Current active model</option>
                      <option value="random">Random (seeded)</option>
                    </select>
                  </Field>
                  {init === 'random' && (
                    <Field label="Random seed">
                      <input className={inputCls} type="number" value={seed} onChange={(e) => setSeed(Number(e.target.value))} />
                    </Field>
                  )}
                  <Field label="Pseudo-count" hint="0 = pure EM (monotone)">
                    <input className={inputCls} type="number" min={0} step={0.1} value={pseudo} onChange={(e) => setPseudo(Math.max(0, Number(e.target.value)))} />
                  </Field>
                </>
              )}
            </div>
            <Button variant="primary" onClick={run} loading={running} disabled={method === 'baum-welch' && !(tol > 0)}>
              <Play className="size-4" /> {method === 'mle' ? 'Run supervised MLE' : 'Run Baum-Welch'}
            </Button>
            <ErrorBox error={method === 'mle' ? mle.error : bw.error} />
          </div>
        </Card>
      </div>

      {running && <Loading label="Training on the backend…" />}

      {result && !running && (
        <>
          <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
            {result.method === 'baum_welch' ? (
              <>
                <Stat
                  label="Convergence"
                  value={
                    <span className="flex items-center gap-2 text-base">
                      {result.converged ? <CheckCircle2 className="size-4 text-emerald-400" /> : <XCircle className="size-4 text-amber-400" />}
                      {result.converged ? 'Converged' : 'Hit max iterations'}
                    </span>
                  }
                  hint={`tolerance ${result.tolerance}`}
                />
                <Stat label="Iterations" value={result.iterations} hint={`of max ${result.max_iterations}`} />
                <Stat label="log L before" value={fmt(result.initial_log_likelihood)} hint={`${result.n_sequences} sequences · ${result.n_observations} actions`} />
                <Stat label="log L after" value={fmt(result.final_log_likelihood)} hint={`+${(result.final_log_likelihood - result.initial_log_likelihood).toFixed(2)}`} />
              </>
            ) : (
              <>
                <Stat label="Sequences" value={result.n_sequences} hint={`${result.n_observations} actions`} />
                <Stat label="Transitions counted" value={result.n_transitions} />
                <Stat label="log P(O) before → after" value={<span className="text-base">{fmt(result.log_likelihood_before)} → {fmt(result.log_likelihood_after)}</span>} />
                <Stat
                  label="log P(O, Q) before → after"
                  value={<span className="text-base">{fmt(result.complete_log_likelihood_before)} → {fmt(result.complete_log_likelihood_after)}</span>}
                  hint="complete-data likelihood (what counting maximises)"
                />
              </>
            )}
          </div>

          {result.method === 'baum_welch' && (
            <Card title="Log-likelihood progression" subtitle="log P(O | λ) summed over all training sequences, after each EM iteration">
              <LikelihoodChart history={result.history} height={280} />
              <p className="mt-2 text-xs text-slate-500">
                {result.monotonic ? 'The curve never decreases, as the EM theory guarantees.' : 'With a pseudo-count the update is a smoothed (MAP-style) EM, so strict monotonicity is not guaranteed.'}{' '}
                EM converges to a local maximum; different initialisations can reach different solutions, and learned states may swap meaning.
              </p>
            </Card>
          )}

          <Card
            title="Before and after training"
            subtitle="Left: parameters used to start · right: estimated parameters"
            action={
              <Button size="sm" variant="primary" onClick={apply} loading={save.loading} disabled={saved !== null}>
                <Save className="size-3.5" /> {saved ? 'Applied' : 'Apply as active model'}
              </Button>
            }
          >
            <ErrorBox error={save.error} />
            {saved && (
              <div className="mb-4">
                <Callout kind="tip">“{saved}” is now the active model. All inference pages use it. Reset it on the Model Configuration page.</Callout>
              </div>
            )}
            <BeforeAfter before={result.before} after={result.after} />
          </Card>
        </>
      )}
    </div>
  )
}

function BeforeAfter({ before, after }: { before: ModelDict; after: ModelDict }) {
  const blocks: { title: string; get: (m: ModelDict) => number[][]; cols: string[]; color?: string; wide?: boolean }[] = [
    { title: 'π (as a row)', get: (m) => [m.pi], cols: [...STATE_SHORT] },
    { title: 'A: transitions', get: (m) => m.A, cols: [...STATE_SHORT] },
    { title: 'B: emissions', get: (m) => m.B, cols: before.observations, wide: true },
  ]
  return (
    <div className="space-y-6">
      {blocks.map((b) => {
        const bv = b.get(before)
        const av = b.get(after)
        const rows = bv.length === 1 ? ['π'] : [...STATE_SHORT]
        return (
          <div key={b.title}>
            <div className="mb-2 text-[0.8125rem] font-medium text-slate-300">{b.title}</div>
            <div className={`grid gap-4 ${b.wide ? 'lg:grid grid-cols-1-cols-2 2xl:grid-cols-3' : 'xl:grid grid-cols-1-cols-3'}`}>
              <div>
                <div className="mb-1 text-xs text-slate-500">before</div>
                <MatrixTable values={bv} rowLabels={rows} colLabels={b.cols} compact color={b.color} format={f3} />
              </div>
              <div>
                <div className="mb-1 text-xs text-slate-500">after</div>
                <MatrixTable values={av} rowLabels={rows} colLabels={b.cols} compact color={b.color} format={f3} rowSums={bv.length > 1} />
              </div>
              <div>
                <div className="mb-1 text-xs text-slate-500">change (after − before)</div>
                <MatrixTable
                  values={av.map((r, i) => r.map((v, j) => v - bv[i][j]))}
                  rowLabels={rows}
                  colLabels={b.cols}
                  compact
                  heat={false}
                  format={(v) => (v === null ? 'n/a' : `${v >= 0 ? '+' : ''}${v.toFixed(3)}`)}
                />
              </div>
            </div>
          </div>
        )
      })}
    </div>
  )
}
