import { ChevronLeft, ChevronRight, FlaskConical, UserRound } from 'lucide-react'
import { useState } from 'react'
import { CountBarChart } from '../charts/Charts'
import { JourneyTimeline, SequenceInline } from '../components/Journey'
import { Badge, Button, Callout, Card, ErrorBox, Loading, PageHeader, Stat, cx, inputCls } from '../components/ui'
import { useAppState } from '../hooks/useAppState'
import { useAsync } from '../hooks/useAsync'
import { navigate } from '../hooks/useRoute'
import { BEHAVIOUR_SHORT, STATE_SHORT } from '../lib/constants'
import { pct } from '../lib/format'
import { api } from '../services/api'
import type { DatasetSequence } from '../types'

const PAGE = 15
const selectCls = inputCls.replace('num ', '').replace('w-full ', 'w-44 ')

export function DatasetPage() {
  const { setSequence } = useAppState()
  const [behaviour, setBehaviour] = useState('')
  const [purchased, setPurchased] = useState<'' | 'true' | 'false'>('')
  const [offset, setOffset] = useState(0)
  const [selected, setSelected] = useState<DatasetSequence | null>(null)
  const summary = useAsync(() => api.datasetSummary(), [])
  const page = useAsync(
    () => api.dataset({ behaviour: behaviour || undefined, purchased: purchased === '' ? undefined : purchased === 'true', limit: PAGE, offset }),
    [behaviour, purchased, offset],
  )

  const open = (s: DatasetSequence, dest: string) => {
    setSequence(s.observations)
    navigate(dest)
  }

  return (
    <div className="space-y-6">
      <PageHeader title="Dataset Explorer">
        Browse the simulated customer sequences used for training. Each sequence was generated by sampling hidden intentions from an archetype-specific Markov chain
        and emitting actions from B, so the true hidden states are recorded alongside the actions.
      </PageHeader>
      <Callout kind="warn" title="Simulated data">
        None of these customers are real. The generator lives in <code className="num">backend/app/services/dataset.py</code> and the data is stored in{' '}
        <code className="num">dataset/synthetic_customers.csv</code> and in SQLite.
      </Callout>

      {summary.data && (
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-3">
          <div className="grid grid-cols-2 gap-3 lg:col-span-1 lg:grid-cols-1">
            <Stat label="Sequences" value={summary.data.total} />
            <Stat label="Purchase rate" value={pct(summary.data.purchase_rate)} />
            <Stat label="Mean length" value={summary.data.mean_length.toFixed(2)} hint="actions per session" />
            <Stat label="Ended by" value={<span className="text-sm">{summary.data.ended_with.map((e) => `${e.ended_with} ${e.count}`).join(' · ')}</span>} />
          </div>
          <Card title="Behaviour labels" className="lg:col-span-1">
            <CountBarChart data={summary.data.behaviours.map((b) => ({ ...b, behaviour: BEHAVIOUR_SHORT[b.behaviour] ?? b.behaviour }))} xKey="behaviour" height={250} angled />
          </Card>
          <Card title="Action frequencies" className="lg:col-span-1">
            <CountBarChart data={summary.data.actions} xKey="action" height={250} />
          </Card>
        </div>
      )}

      <div className="grid grid-cols-1 gap-5 xl:grid-cols-[minmax(0,1.5fr)_minmax(0,1fr)]">
        <Card
          title="Sequences"
          subtitle={page.data ? `${page.data.total} matching` : undefined}
          action={
            <div className="flex flex-wrap gap-2">
              <select className={selectCls} value={behaviour} onChange={(e) => { setBehaviour(e.target.value); setOffset(0) }}>
                <option value="">All behaviours</option>
                {summary.data?.behaviours.map((b) => (
                  <option key={b.behaviour} value={b.behaviour}>
                    {b.behaviour}
                  </option>
                ))}
              </select>
              <select className={selectCls} value={purchased} onChange={(e) => { setPurchased(e.target.value as '' | 'true' | 'false'); setOffset(0) }}>
                <option value="">Any outcome</option>
                <option value="true">Purchased</option>
                <option value="false">No purchase</option>
              </select>
            </div>
          }
          pad={false}
        >
          <ErrorBox error={page.error} />
          {page.loading && !page.data ? (
            <div className="px-5">
              <Loading />
            </div>
          ) : (
            page.data && (
              <>
                <div className="overflow-x-auto">
                  <table className="w-full text-[0.8125rem]">
                    <thead className="text-left text-slate-500">
                      <tr>
                        <th className="px-4 py-2 font-medium">ID</th>
                        <th className="px-2 py-2 font-medium">Behaviour</th>
                        <th className="px-2 py-2 font-medium">Actions</th>
                        <th className="px-4 py-2 text-right font-medium">Len</th>
                      </tr>
                    </thead>
                    <tbody>
                      {page.data.items.map((s) => (
                        <tr
                          key={s.id}
                          onClick={() => setSelected(s)}
                          className={cx('cursor-pointer border-t border-ink-700/60 transition-colors hover:bg-ink-800/60', selected?.id === s.id && 'bg-accent/10')}
                        >
                          <td className="num px-4 py-2 whitespace-nowrap text-slate-400">{s.customer_id}</td>
                          <td className="px-2 py-2">
                            <Badge color={s.purchased ? "#1fa97c" : undefined}>{s.behaviour}</Badge>
                          </td>
                          <td className="px-2 py-2">
                            <SequenceInline seq={s.observations} />
                          </td>
                          <td className="num px-4 py-2 text-right text-slate-400">{s.length}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
                <div className="flex items-center justify-between border-t border-ink-700/70 px-4 py-2.5 text-xs text-slate-500">
                  <span>
                    {page.data.total === 0 ? 0 : offset + 1}-{Math.min(offset + PAGE, page.data.total)} of {page.data.total}
                  </span>
                  <div className="flex gap-1">
                    <Button size="sm" variant="ghost" disabled={offset === 0} onClick={() => setOffset(Math.max(0, offset - PAGE))}>
                      <ChevronLeft className="size-4" />
                    </Button>
                    <Button size="sm" variant="ghost" disabled={offset + PAGE >= page.data.total} onClick={() => setOffset(offset + PAGE)}>
                      <ChevronRight className="size-4" />
                    </Button>
                  </div>
                </div>
              </>
            )
          )}
        </Card>

        <Card title="Sequence detail" subtitle={selected ? `${selected.customer_id} · archetype ${selected.archetype.replace('_', ' ')}` : 'Select a row'}>
          {selected ? (
            <div className="space-y-4">
              <JourneyTimeline seq={selected.observations} states={selected.hidden_states.map((h) => STATE_SHORT.indexOf(h as (typeof STATE_SHORT)[number]))} />
              <p className="text-xs text-slate-500">
                Chips under each action are the <strong className="text-slate-300">true simulated hidden states</strong>. Real data would not have them; compare
                them with what Viterbi infers.
              </p>
              <div className="grid grid-cols-2 gap-2 text-[0.8125rem]">
                <div className="text-slate-500">Behaviour</div>
                <div className="text-slate-200">{selected.behaviour}</div>
                <div className="text-slate-500">Session ended by</div>
                <div className="text-slate-200">{selected.ended_with}</div>
                <div className="text-slate-500">Purchased</div>
                <div className="text-slate-200">{selected.purchased ? 'Yes' : 'No'}</div>
              </div>
              <div className="flex flex-wrap gap-2">
                <Button size="sm" variant="primary" onClick={() => open(selected, '/simulator')}>
                  <UserRound className="size-3.5" /> Load into simulator
                </Button>
                <Button size="sm" variant="secondary" onClick={() => open(selected, '/lab/viterbi')}>
                  <FlaskConical className="size-3.5" /> Decode with Viterbi
                </Button>
              </div>
            </div>
          ) : (
            <p className="text-sm text-slate-500">Click a sequence to inspect its actions and simulated hidden states.</p>
          )}
        </Card>
      </div>
    </div>
  )
}
