router = APIRouter(prefix="/api", tags=["configuration"])

STATE_DESCRIPTIONS = {
    "Browsing": "Exploring the catalogue without a specific goal. Mostly views products; low commitment.",
    "Interested": "Has found something relevant. Compares, adds to cart, may start checkout.",
    "Ready to Purchase": "Has effectively decided. Very likely to complete a purchase soon.",
}

