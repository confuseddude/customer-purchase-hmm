@router.get("/dataset")
def dataset(
    behaviour: str | None = None,
    purchased: bool | None = None,
    limit: int = Query(25, ge=1, le=200),
    offset: int = Query(0, ge=0),
):
    total, rows = db.list_sequences(behaviour, purchased, limit, offset)
    return {"total": total, "limit": limit, "offset": offset, "items": rows,
            "note": "Simulated sequences generated by app/services/dataset.py (seed 42)."}


@router.get("/dataset/summary")
def dataset_summary():
    rows = db.all_sequences()
    behaviour = Counter(r["behaviour"] for r in rows)
    actions = Counter(o for r in rows for o in r["observations"])
    lengths = Counter(r["length"] for r in rows)
    ended = Counter(r["ended_with"] for r in rows)
    return {
        "total": len(rows),
        "purchase_rate": sum(r["purchased"] for r in rows) / max(len(rows), 1),
        "mean_length": float(np.mean([r["length"] for r in rows])) if rows else 0.0,
        "behaviours": [{"behaviour": b, "count": behaviour.get(b, 0)} for b in BEHAVIOURS],
        "actions": [{"action": a, "count": actions.get(a, 0)} for a in OBSERVATIONS],
        "lengths": [{"length": k, "count": lengths[k]} for k in sorted(lengths)],
        "ended_with": [{"ended_with": k, "count": v} for k, v in ended.most_common()],
    }


@router.get("/dataset/{seq_id}")
def dataset_item(seq_id: int):
    row = db.get_sequence(seq_id)
    if row is None:
        raise HTTPException(404, f"Sequence {seq_id} not found.")
    return row


