@router.get("/learn/likelihood-curve")
def likelihood_curve(k: int = Query(7, ge=0), n: int = Query(10, ge=1, le=1000), points: int = Query(101, ge=3, le=501)):
    """Bernoulli likelihood L(p) = p^k (1-p)^(n-k) used to explain MLE in the Learn chapter."""
    if k > n:
        raise HTTPException(422, "k cannot exceed n.")
    p = np.linspace(0, 1, points)
    with np.errstate(divide="ignore"):
        log_l = k * np.log(p) + (n - k) * np.log(1 - p)
    lik = np.exp(log_l)
    return jsonable(
        {
            "k": k,
            "n": n,
            "mle": k / n,
            "max_likelihood": float((k / n) ** k * (1 - k / n) ** (n - k)),
            "curve": [{"p": float(pp), "likelihood": float(ll), "log_likelihood": float(lg)}
                      for pp, ll, lg in zip(p, lik, log_l)],
        }
    )
